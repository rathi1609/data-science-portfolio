print("Counting from 1 to 10:")

for number in range(1, 11):
    print(number)

print("\nEven numbers from 1 to 20:")

for number in range(2, 21, 2):
    print(number)

print("\nMultiplication table of 5:")

for number in range(1, 11):
    print(f"5 x {number} = {5 * number}")
